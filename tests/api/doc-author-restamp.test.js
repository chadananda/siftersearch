// doc-author-restamp (Qdrant payload from current rows) + oceanoflights-slug-authors (slug → figure) + doc-corrections religion.
import { describe, it, expect } from 'vitest';
import { docAuthorRestampJob } from '../../api/lib/ops/doc-author-restamp-job.js';
import { oceanoflightsSlugAuthorsJob, slugFigure } from '../../api/lib/ops/oceanoflights-slug-authors-job.js';
import { docCorrectionsJob } from '../../api/lib/ops/doc-corrections-job.js';

describe('slugFigure', () => {
  it.each([['file-bahaullah-inba-065', 'Bahá’u’lláh'], ['file-autogenerated-bahaullah-x', 'Bahá’u’lláh'], ['file-abdul-baha-x', '‘Abdu’l-Bahá'], ['file-autogenerated-abdul-baha-x', '‘Abdu’l-Bahá'],
    ['file-tablets-of-abdul-baha-abbas-1', '‘Abdu’l-Bahá'], ['file-bab-selections', 'The Báb'], ['file-Shoghi-Effendi-x', 'Shoghi Effendi']])('%s', (s, a) => expect(slugFigure(s)).toEqual({ author: a, religion: "Baha'i" }));
  it.each(['file-baba-x', 'file-other-x', 'file-publications-x', 'Shoghi Effendi'])('%s unchanged', (s) => expect(slugFigure(s)).toBeNull());
});

describe('doc-author-restamp', () => {
  it('groups docs by payload and stamps every collection', async () => {
    const calls = [];
    const docs = async ({ ids }) => ({ docs: ids.map((id) => ({ id, author: id < 3 ? '‘Abdu’l-Bahá' : 'The Báb', religion: id === 4 ? null : "Baha'i" })) });
    const r = await docAuthorRestampJob({ ids: [1, 2, 3, 4], collections: ['a', 'b'], batch: 1 }, { docs, qd: async (path, body) => calls.push([path, body]), draining: () => false });
    expect(r).toMatchObject({ docs: 4, groups: 3, calls: 2 * (2 + 1 + 1), errors: 0 });
    expect(calls[0]).toEqual(['/collections/a/points/payload?wait=false', { payload: { author: '‘Abdu’l-Bahá', author_fold: 'abdulbaha', religion: "Baha'i" }, filter: { must: [{ key: 'doc_id', match: { any: [1] } }] } }]);
    expect(calls.find(([, b]) => b.filter.must[0].match.any[0] === 4)[1].payload).not.toHaveProperty('religion');
  });
  it('with was, one call per payload matches any old author key (paragraph writers kept)', async () => {
    const calls = [];
    const docs = async ({ ids }) => ({ docs: ids.map((id) => ({ id, author: 'Bahá’u’lláh', religion: "Baha'i" })) });
    const r = await docAuthorRestampJob({ ids: [1, 2], was: { 1: 'file-bahaullah-a', 2: 'file-bahaullah-b' }, collections: ['a'] }, { docs, qd: async (path, body) => calls.push(body), draining: () => false });
    expect(r).toMatchObject({ groups: 1, calls: 1 });
    expect(calls[0].filter.must).toEqual([{ key: 'doc_id', match: { any: [1, 2] } }, { key: 'author_fold', match: { any: ['filebahaullaha', 'filebahaullahb'] } }]);
    expect(calls[0].payload).toEqual({ author: 'Bahá’u’lláh', author_fold: 'bahaullah', religion: "Baha'i" });
  });
  it('retries a failed call once, then records it', async () => {
    let n = 0;
    const docs = async ({ ids }) => ({ docs: ids.map((id) => ({ id, author: 'The Báb', religion: "Baha'i" })) });
    const flaky = await docAuthorRestampJob({ ids: [1], collections: ['a'] }, { docs, qd: async () => { if (n++ === 0) throw new Error('timeout'); }, draining: () => false });
    expect(flaky).toMatchObject({ calls: 1, errors: 0, failed: [] });
    const dead = await docAuthorRestampJob({ ids: [1], collections: ['a'] }, { docs, qd: async () => { throw new Error('boom'); }, draining: () => false });
    expect(dead).toMatchObject({ calls: 0, errors: 1, failed: [{ collection: 'a', ids: [1], error: 'boom' }] });
  });
  it('yields on drain with the remaining ids', async () => {
    const r = await docAuthorRestampJob({ ids: [1, 2] }, { docs: async () => ({ docs: [] }), qd: async () => {}, draining: () => true });
    expect(r).toMatchObject({ yielded: true, resume: { ids: [1, 2] } });
  });
});

describe('oceanoflights-slug-authors', () => {
  const D = '/tank/site2rag/websites_md/oceanoflights.org/';
  const rows = [{ id: 1, title: 't', author: 'file-bahaullah-a', file_path: `../../../../../..${D}a.md` }, { id: 2, title: 't', author: 'file-other-x', file_path: `${D}b.md` }, { id: 3, title: 't', author: 'file-bab-x', file_path: 'elsewhere/c.md' }];
  const docs = async ({ afterId }) => ({ docs: afterId ? [] : rows });
  it('dry run counts and changes nothing', async () => {
    const r = await oceanoflightsSlugAuthorsJob({}, { docs, corrections: async () => { throw new Error('no'); }, enqueue: async () => { throw new Error('no'); } });
    expect(r).toMatchObject({ scanned: 2, perFigure: { 'Bahá’u’lláh': 1 }, unchanged: { 'file-other': 1 }, changed: 1, restamp: null });
  });
  it('write corrects then queues the restamp', async () => {
    const q = [];
    const r = await oceanoflightsSlugAuthorsJob({ write: true }, { docs, corrections: async ({ fixes }) => ({ changes: fixes }), enqueue: async (...a) => { q.push(a); return 7; } });
    expect(q).toEqual([['doc-author-restamp', { ids: [1], was: { 1: 'file-bahaullah-a' } }, 'oceanoflights-slug-authors']]);
    expect(r.restamp).toBe(7);
  });
});

describe('doc-corrections religion', () => {
  it('writes a changed religion, skips an unchanged one', async () => {
    const log = [];
    const doc = { id: 5, title: 't', author: 'a', religion: null, file_path: 'x' };
    const deps = { get: async () => doc, setReligion: async (id, r) => log.push([id, r]) };
    await docCorrectionsJob({ write: true, fixes: [{ id: 5, religion: "Baha'i" }] }, deps);
    await docCorrectionsJob({ write: true, fixes: [{ id: 5, religion: "Baha'i" }] }, { ...deps, get: async () => ({ ...doc, religion: "Baha'i" }) });
    expect(log).toEqual([[5, "Baha'i"]]);
  });
});
