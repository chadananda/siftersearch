// r16 11-11 (Shaykh Aḥmad): the writer told the reader "(which I can cite by title only)", and cited a slug-titled .docx scrape.
import { describe, it, expect } from 'vitest';
import { dropLinkAside, plainSources, formPass } from '../../api/lib/assistant/lint.js';
import { unslug, anisUserPayload } from '../../api/lib/assistant/prompt.js';

describe('link asides never reach the reader', () => {
  it('drops the parenthetical, keeps the sentence', () => {
    const t = 'In his tablet on Shaykh Aḥmad and Siyyid Káẓim (which I can cite by title only), he describes the same arc.';
    const r = dropLinkAside(t);
    expect(r.fixed).toBe(1); expect(r.text).toBe('In his tablet on Shaykh Aḥmad and Siyyid Káẓim, he describes the same arc.');
    expect(dropLinkAside('See *Memorials* (no link available).').text).toBe('See *Memorials*.');
  });
  it('leaves ordinary parentheses and block quotes alone; formPass records it', () => {
    expect(dropLinkAside('He cited the Qur’án (by title and verse) often.').fixed).toBe(0);
    expect(dropLinkAside('> a line (which I can cite by title only)').fixed).toBe(0);
    expect(formPass('A tablet (which I can only cite by title) says so.').repairs.link_aside).toBe(1);
  });
});

describe('a slug-titled scrape takes the title of the book it is', () => {
  const db = { source_title: 'The Dawn-Breakers', citation_url: 'https://oceanlibrary.com/dawn-breakers_nabil/?paraId=para_156&selectionString=x', text: 'a' };
  const slug = { source_title: 'shoghi-effendi-trans-011-the-dawn-breakers_en', citation_url: 'https://oceanoflights.org/file/autogenerated/shoghi-effendi-trans-011-the-dawn-breakers_en.docx', text: 'b' };
  it('matching tail → the book title and its public book link', () => {
    const [, s] = unslug([db, slug]);
    expect(s.source_title).toBe('The Dawn-Breakers'); expect(s.citation_url).toBe('https://oceanlibrary.com/dawn-breakers_nabil/');
    expect(anisUserPayload({ question: 'q', passages: [db, slug] })).not.toContain('.docx');
  });
  it('no matching book → unchanged', () => {
    const other = { ...db, source_title: 'God Passes By' };
    expect(unslug([other, slug])[1]).toBe(slug);
  });
});

describe('retrieval talk becomes source talk', () => {
  it('rewrites the r17 phrasings, counts them, leaves quotes and ordinary uses', () => {
    const r = plainSources('The first passage returned, a Tablet, does not speak of him. The library\'s results here did not include his writings. The passages here show the opening. The passages don\'t record his reason.');
    expect(r.text).toBe('The first source I found, a Tablet, does not speak of him. The sources I found did not include his writings. The sources show the opening. The sources don\'t record his reason.');
    expect(r.fixed).toBe(4);
    expect(plainSources('This passage of the Íqán is famous.').fixed).toBe(0);
    expect(plainSources('> The passages here show it').fixed).toBe(0);
    expect(formPass('The passages here show the opening.').repairs.retrieval_talk).toBe(1);
  });
});
