// Dewey benchmark — build the cases: pick held documents through the public API, download their text, make every
// scenario of planning/dewey-benchmark-plan.md from them (formats by pandoc, scans by render-scan.py, OCR'd PDFs by
// tesseract), plus texts we do not hold (Project Gutenberg, checked absent). Writes tmp/dewey-bench/cases/ + manifest.json.
// usage: node scripts/dewey-bench/build.mjs   (DEWEY_KEY or tmp/dewey-test-key: an API key with Dewey access)
import { mkdir, writeFile, readFile } from 'fs/promises';
import { existsSync } from 'fs';
import { execFileSync } from 'child_process';
import { join } from 'path';
import * as V from './variants.mjs';

const API = process.env.API_URL || 'https://api.siftersearch.com';
const KEY = process.env.DEWEY_KEY || (await readFile('tmp/dewey-test-key', 'utf8').catch(() => '')).match(/sk_[\w-]+/)?.[0];
const OUT = 'tmp/dewey-bench', CASES = join(OUT, 'cases');
const H = { 'X-API-Key': KEY };
const get = async (path) => { const r = await fetch(`${API}${path}`, { headers: H }); if (!r.ok) throw new Error(`${path}: ${r.status}`); return r.json(); };

/** A held document's full text (the two-step download). */
async function textOf(id) {
  const { downloadUrl } = await get(`/api/documents/${id}/download?format=txt`);
  const t = await (await fetch(downloadUrl)).text();
  return t.replace(/^[\s\S]*?\n---\n/, '').trim();   // the header block (Title/Author/Language)
}
async function pick(q, n, { min = 20, max = 3000 } = {}) {
  // the listing is alphabetical: read several pages and take every k-th match, so the picks spread across the shelf
  const all = [];
  for (const offset of [0, 100, 200, 300, 400, 500]) {
    const { documents = [] } = await get(`/api/v1/library/documents?${new URLSearchParams({ limit: '100', offset: String(offset), ...q })}`).catch(() => ({}));
    all.push(...documents);
    if (documents.length < 100) break;
  }
  const ok = all.filter((d) => d.paragraphCount >= min && d.paragraphCount <= max && !/^file-autogenerated|untitled|^\.\.\./i.test(`${d.author} ${d.title}`))
    .filter((d, i, a) => a.findIndex((x) => x.title === d.title) === i);
  const step = Math.max(1, Math.floor(ok.length / n));
  return ok.filter((_, i) => i % step === Math.floor(step / 2)).slice(0, n);
}
async function gutenberg(id) {
  const t = await (await fetch(`https://www.gutenberg.org/cache/epub/${id}/pg${id}.txt`)).text();
  const s = t.indexOf('*** START OF'), e = t.indexOf('*** END OF');
  return t.slice(t.indexOf('\n', s) + 1, e > 0 ? e : undefined).replace(/\r/g, '').replace(/([^\n])\n(?!\n)/g, '$1 ').trim();
}

const SOURCES = [
  ['long', { religion: "Baha'i", collection: "Baha'i Books" }, 3, { min: 150 }],
  ['long', { religion: "Baha'i", collection: 'Books' }, 2, { min: 150 }],
  ['short', { religion: "Baha'i", collection: 'Pilgrim Notes' }, 3, { min: 5, max: 60 }],
  ['short', { religion: "Baha'i", collection: 'Administrative' }, 2, { min: 5, max: 40 }],
  ['long', { religion: 'Christian', collection: 'Church Fathers' }, 1, { min: 150 }],
  ['long', { religion: 'Islam', collection: 'History and Biography' }, 1, { min: 150 }],
  ['long', { religion: 'Buddhist', collection: 'Pali Canon' }, 1, { min: 100 }],
  ['foreign', { language: 'fr' }, 1, { min: 30 }],
  ['foreign', { language: 'fa' }, 1, { min: 30 }],
  ['foreign', { language: 'ar' }, 1, { min: 20 }],
];
// texts we do not hold (title search empty, 10-18); 'author' marks the same-author-as-a-held-work case
const NOT_HELD = [
  { id: 621, title: 'The Varieties of Religious Experience', author: 'William James' },
  // HELD after all: the library has "Confessions of St. Augustine" (#17295) — the title lookup missed it, Dewey's text did not
  // (10-18). Kept as a positive: a held work in another edition from another source.
  { id: 3296, title: 'The Confessions of Saint Augustine', author: 'Augustine', held: 17295 },
  { id: 1695, title: 'The Man Who Was Thursday', author: 'G. K. Chesterton', sameAuthorAs: 'Orthodoxy' },
];

await mkdir(CASES, { recursive: true });
const manifest = [];
const sh = (cmd, args) => execFileSync(cmd, args, { stdio: ['ignore', 'pipe', 'pipe'] }).toString();
async function add(id, scenario, expect, text, { format = 'txt', source = null, scanQuality = null, pages = 30, note = '' } = {}) {
  const base = join(CASES, id);
  const md = `${base}.md`;
  await writeFile(md, text);
  let file = md;
  if (['docx', 'html', 'epub', 'rtf', 'odt'].includes(format)) { file = `${base}.${format}`; sh('pandoc', ['-f', 'markdown-smart', md, '-s', '--metadata', `title=${id}`, '-o', file]); }
  else if (format === 'txt') { file = `${base}.txt`; await writeFile(file, text); }
  else if (format === 'scan' || format === 'ocrpdf') {
    file = `${base}.pdf`;
    sh('python3', ['scripts/dewey-bench/render-scan.py', md, file, '--quality', scanQuality || 'clean', '--max-pages', String(pages)]);
    if (format === 'ocrpdf') {   // a searchable PDF: the scan with tesseract's text layer (the "_OCRd.pdf" of a drive)
      const dir = `${base}-pages`; await mkdir(dir, { recursive: true });
      sh('pdftoppm', ['-r', '100', '-gray', '-png', file, join(dir, 'p')]);   // 100 dpi: the API takes ≤ 30 MB
      const list = sh('sh', ['-c', `ls ${dir}/p-*.png`]).trim().split('\n');
      await writeFile(join(dir, 'list.txt'), list.join('\n'));
      sh('tesseract', [join(dir, 'list.txt'), base, 'pdf']);   // writes <base>.pdf
    }
  }
  manifest.push({ id, scenario, expect, file, format, source, note, words: text.split(/\s+/).length });
}

const held = [];
for (const [kind, q, n, lim] of SOURCES) for (const d of await pick(q, n, lim)) held.push({ ...d, kind, text: await textOf(d.id) });
const nots = [];
for (const g of NOT_HELD) nots.push({ ...g, text: await gutenberg(g.id) });
const fresh = nots.filter((g) => !g.held && !g.sameAuthorAs);
const prose = fresh[0].text;   // new prose for compilations, commentary, supersets — never a held text
const cap = (t, words = 60000) => t.split(/(?<=\n\n)/).reduce((a, p) => (a.n < words ? { s: a.s + p, n: a.n + p.split(/\s+/).length } : a), { s: '', n: 0 }).s;

for (const d of held) {
  const t = cap(d.text), tag = `${d.kind}-${d.id}`, src = { id: d.id, title: d.title, author: d.author, language: d.language };
  const latin = !['fa', 'ar'].includes(d.language);
  await add(`P1-${tag}`, 'P1 same text .txt', ['held'], t, { source: src });
  await add(`P5-${tag}`, 'P5 OCR errors', ['held'], V.ocrNoise(t, { header: d.title.slice(0, 40), seed: d.id }), { source: src });
  await add(`P6-${tag}`, 'P6 retyped', ['held'], V.retype(t, { seed: d.id }), { source: src, format: 'docx' });
  if (latin) await add(`P3-${tag}`, 'P3 clean scan', ['held'], t, { source: src, format: 'scan', pages: 12 });
  if (latin) await add(`P4-${tag}`, 'P4 bad scan', ['held', 'undetermined'], t, { source: src, format: 'scan', scanQuality: 'bad', pages: 8 });
  if (d.kind === 'long') {
    await add(`P2d-${tag}`, 'P2 format .docx', ['held'], t, { source: src, format: 'docx' });
    await add(`P2h-${tag}`, 'P2 format .html', ['held'], t, { source: src, format: 'html' });
    await add(`P2e-${tag}`, 'P2 format .epub', ['held'], t, { source: src, format: 'epub' });
    await add(`P2r-${tag}`, 'P2 format .rtf', ['held'], t, { source: src, format: 'rtf' });
    if (latin) await add(`P2p-${tag}`, "P2 OCR'd PDF (text layer)", ['held'], t, { source: src, format: 'ocrpdf', pages: 15 });   // no Arabic-script shaping in the renderer
    await add(`P7-${tag}`, 'P7 other edition', ['held'], V.edition(t, { title: d.title, seed: d.id }), { source: src, format: 'docx' });
    await add(`P8-${tag}`, 'P8 abridged', ['held'], V.abridge(t, { seed: d.id }), { source: src });
    await add(`P9-${tag}`, 'P9 excerpt', ['held'], V.excerpt(t, { seed: d.id }), { source: src });
    await add(`P13-${tag}`, 'P13 front matter only', ['held'], V.frontOnly(t), { source: src, note: 'held — and must read as a fragment' });
    await add(`P10-${tag}`, 'P10 superset (held + new chapters)', ['partly-held'], V.superset(t, prose), { source: src });
  }
}
const longs = held.filter((d) => d.kind === 'long');
await add('G1-compilation', 'G1 new compilation (quotes from held works)', ['possible', 'not-held'], V.compilation(longs.map((d) => d.text), prose));
await add('G2-commentary', 'G2 commentary quoting a held work', ['possible', 'not-held'], V.commentary(longs[0].text, prose), { source: { id: longs[0].id, title: longs[0].title } });
for (const g of nots) {
  const t = cap(g.text, 40000);
  if (g.held) {
    await add(`P14-${g.id}`, 'P14 held work, other edition from another source', ['held'], t, { note: `${g.title} — held as #${g.held}` });
    await add(`P14s-${g.id}`, 'P14 held work, other edition — scan', ['held'], t, { format: 'scan', pages: 12, note: `${g.title} — held as #${g.held}` });
    continue;
  }
  await add(`N1-${g.id}`, g.sameAuthorAs ? 'N3 same author, other work' : 'N1 not held', ['not-held', 'not-found-by-title'], t, { note: g.title });
  await add(`N1s-${g.id}`, 'N1 not held — scan', ['not-held', 'not-found-by-title'], t, { format: 'scan', pages: 12, note: g.title });
}
for (const d of longs.slice(0, 2)) await add(`N2-${d.id}`, 'N2 same title+author as a held work, other text', ['not-held', 'not-found-by-title'], V.sameTitle(d.title, d.author || '', cap(prose, 20000)), { note: `title of #${d.id}` });
await add('N4-blank', 'N4 blank/noise scan', ['undetermined'], 'x\n\n'.repeat(400), { format: 'scan', scanQuality: 'blank' });

await writeFile(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 1));
console.log(`${manifest.length} cases from ${held.length} held documents (${[...new Set(held.map((d) => d.kind))].join(', ')}) and ${nots.length} texts not held → ${OUT}/manifest.json`);
for (const d of held) console.log(`  #${d.id} ${d.kind} ${d.language} ${d.paragraphCount}¶  ${d.title.slice(0, 70)}`);
if (!existsSync(join(OUT, 'manifest.json'))) process.exit(1);
