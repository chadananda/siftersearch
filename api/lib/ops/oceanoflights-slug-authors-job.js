// OCEANOFLIGHTS SLUG AUTHORS. oceanoflights.org docs whose author is a file slug ('file-bahaullah-inba-065') get the Central
// Figure the slug prefix names (deterministic); other slugs are left and counted by prefix. Dry by default. write:true applies
// author + religion through doc-corrections, then queues doc-author-restamp for the changed ids.
// params { write = false, limit (docs to change this run), sample = 10 }.
import { listDocs } from '../docs-repo.js';
import { docCorrectionsJob } from './doc-corrections-job.js';

// stored paths are relative ('../../../../../../tank/site2rag/…'), so match the directory anywhere in the path
const DIR = '/site2rag/websites_md/oceanoflights.org/';
const FIGURES = [[/^bahaullah-/, 'Bahá’u’lláh'], [/^(?:abdul-baha|tablets-of-abdul-baha-abbas)-/, '‘Abdu’l-Bahá'], [/^bab-/, 'The Báb'], [/^shoghi-effendi-/, 'Shoghi Effendi']];

/** 'file-autogenerated-bahaullah-x' → { author, religion }; null when the prefix names no figure. */
export function slugFigure(slug) {
  const s = String(slug || '').toLowerCase().replace(/^file-/, '').replace(/^autogenerated-/, '');
  const hit = FIGURES.find(([re]) => re.test(s));
  return hit ? { author: hit[1], religion: "Baha'i" } : null;
}

export async function oceanoflightsSlugAuthorsJob({ write = false, limit = Infinity, sample = 10 } = {}, deps = {}) {
  const { docs = listDocs, corrections = docCorrectionsJob, enqueue = async (n, p, by) => (await import('../repos/ops-report-repo.js')).enqueue(n, p, by) } = deps;
  const out = { write, listed: 0, off_path: [], scanned: 0, perFigure: {}, unchanged: {}, sample: [], changed: 0, restamp: null };
  const fixes = [];
  for (let afterId = 0; ;) {
    const page = (await docs({ scope: 'live', sourceSite: 'oceanoflights.org', authorLike: 'file-%', afterId, fields: ['id', 'title', 'author', 'religion', 'file_path'], limit: 1000, count: false })).docs || [];
    if (!page.length) break;
    afterId = page[page.length - 1].id;
    out.listed += page.length;
    for (const d of page) {
      // listed but skipped: the first few paths shown, so a path-layout change is visible in the dry run
      if (!String(d.file_path || '').includes(DIR) || !/^file-/.test(d.author || '')) { if (out.off_path.length < 3) out.off_path.push([d.id, d.file_path ?? null]); continue; }
      out.scanned++;
      const f = slugFigure(d.author);
      if (!f) { const p = d.author.split('-').slice(0, 2).join('-'); out.unchanged[p] = (out.unchanged[p] || 0) + 1; continue; }
      out.perFigure[f.author] = (out.perFigure[f.author] || 0) + 1;
      if (out.sample.length < sample) out.sample.push({ id: d.id, title: d.title, was: d.author, now: f.author });
      if (fixes.length < limit) fixes.push({ id: d.id, ...f, was: d.author });
    }
  }
  out.changed = fixes.length;
  if (write && fixes.length) {
    const ids = [];
    for (let i = 0; i < fixes.length; i += 500) {
      const r = await corrections({ fixes: fixes.slice(i, i + 500).map(({ was, ...f }) => f), write: true });
      ids.push(...r.changes.map((c) => c.id));
    }
    const was = Object.fromEntries(fixes.filter((f) => ids.includes(f.id)).map((f) => [f.id, f.was]));
    out.restamp = ids.length ? await enqueue('doc-author-restamp', { ids, was }, 'oceanoflights-slug-authors') : null;
  }
  return out;
}
